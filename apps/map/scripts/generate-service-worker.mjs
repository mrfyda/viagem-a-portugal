// Post-export offline pass: a service worker + web manifest for the map.
//
// The Visit outbox already survives offline (src/lib/visitStore.ts); this
// completes "durable by default" for the surface itself — rural Trás-os-Montes
// is exactly where the signal dies. Strategy:
//
//   - Precache the app shell (index.html + the hashed _expo bundles) at
//     install, keyed by a content hash so a new build swaps cleanly.
//   - Navigations are network-first (a fresh index.html whenever online),
//     falling back to whatever page is cached, then to the shell.
//   - Map tiles/glyphs/sprites (tiles.openfreemap.org) and Google Fonts are
//     cache-first: the field use case is revisiting an area already seen.
//     The tile cache is capped so it can't grow without bound.
//
// Registration happens in src/lib/swRegister.web.ts (production only). Runs
// automatically after export via the `export:web` package script.

import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "..", "dist");

const BASE = (process.env.EXPO_BASE_URL || "").replace(/\/+$/, "");
const SITE_BASE = BASE.replace(/\/map$/, "");

// --- collect the shell ------------------------------------------------------

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

const shell = [
  "index.html",
  ...walk(join(dist, "_expo"))
    .filter((p) => /\.(js|css)$/.test(p))
    .map((p) => relative(dist, p).replaceAll("\\", "/")),
].map((p) => `${BASE}/${p}`);

const version = createHash("sha256")
  .update(shell.join("\n"))
  .digest("hex")
  .slice(0, 12);

// --- service worker ---------------------------------------------------------

const sw = `/* generated by scripts/generate-service-worker.mjs — do not edit */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = \`shell-\${VERSION}\`;
const TILE_CACHE = "tiles-v1";
const FONT_CACHE = "fonts-v1";
const PAGE_CACHE = "pages-v1";
const SHELL = ${JSON.stringify(shell)};
const INDEX = ${JSON.stringify(`${BASE}/index.html`)};
const TILE_HOSTS = ["tiles.openfreemap.org"];
const FONT_HOSTS = ["fonts.googleapis.com", "fonts.gstatic.com"];
const MAX_TILES = 800;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  const keep = new Set([SHELL_CACHE, TILE_CACHE, FONT_CACHE, PAGE_CACHE]);
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => !keep.has(k)).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

// Cache-first with a size cap: the map revisits the same tiles constantly and
// the cap keeps a long trip from filling the origin's quota.
async function cacheFirst(cacheName, request, cap) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok || response.type === "opaque") {
    await cache.put(request, response.clone());
    if (cap) {
      const keys = await cache.keys();
      if (keys.length > cap) await cache.delete(keys[0]);
    }
  }
  return response;
}

// Fresh page when online, cached page (then the shell) when not.
async function navigationHandler(request) {
  const pages = await caches.open(PAGE_CACHE);
  try {
    const response = await fetch(request);
    if (response.ok) await pages.put(request, response.clone());
    return response;
  } catch {
    return (
      (await pages.match(request, { ignoreSearch: true })) ??
      (await caches.match(INDEX)) ??
      Response.error()
    );
  }
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);

  if (request.mode === "navigate") {
    event.respondWith(navigationHandler(request));
    return;
  }
  if (url.origin === self.location.origin) {
    event.respondWith(
      caches.match(request).then((hit) => hit ?? fetch(request)),
    );
    return;
  }
  if (TILE_HOSTS.includes(url.hostname)) {
    event.respondWith(cacheFirst(TILE_CACHE, request, MAX_TILES));
    return;
  }
  if (FONT_HOSTS.includes(url.hostname)) {
    event.respondWith(cacheFirst(FONT_CACHE, request));
  }
});
`;

writeFileSync(join(dist, "sw.js"), sw);

// --- web manifest -----------------------------------------------------------

const manifest = {
  name: "Viagem a Portugal — mapa interativo",
  short_name: "Viagem a Portugal",
  description:
    "Mapa interativo de todos os lugares de Viagem a Portugal de José Saramago.",
  lang: "pt-PT",
  start_url: `${BASE}/`,
  scope: `${BASE}/`,
  display: "standalone",
  background_color: "#ffffff",
  theme_color: "#0a5a3a",
  icons: [
    {
      src: `${BASE}/apple-touch-icon.png`,
      sizes: "180x180",
      type: "image/png",
    },
    {
      src: `${SITE_BASE}/assets/logo.png`,
      sizes: "512x512",
      type: "image/png",
      purpose: "any",
    },
  ],
};
writeFileSync(join(dist, "manifest.webmanifest"), JSON.stringify(manifest, null, 2));

console.log(
  `[generate-service-worker] sw.js v${version} (${shell.length} shell assets) + manifest.webmanifest`,
);
